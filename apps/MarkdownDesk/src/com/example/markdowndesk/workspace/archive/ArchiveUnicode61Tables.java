    static boolean isAlnum(int codePoint) {
        if (codePoint < 128) {
            return (ASCII_SEPARATORS[codePoint >>> 5] & (1 << (codePoint & 31))) == 0;
        }
        // Range start in the high bits, length in the low ten.
        int separator = SEPARATORS[floor(SEPARATORS, (codePoint << 10) | 1023, 0)];
        return codePoint >= (separator >>> 10) + (separator & 1023);
    }

    static boolean isDiacritic(int codePoint) {
        if (codePoint < 768 || codePoint > 817) return false;
        int index = codePoint - 768;
        int mask = index < 32 ? 0x08029FDF : 0x000361F8;
        return (mask & (1 << (index & 31))) != 0;
    }

    static int fold(int codePoint) {
        if (codePoint < 128) {
            return codePoint >= 'A' && codePoint <= 'Z' ? codePoint + ('a' - 'A') : codePoint;
        }
        if (codePoint >= 65536) {
            return codePoint >= 66560 && codePoint < 66600 ? codePoint + 40 : codePoint;
        }
        // Packed range start, flags, length. Flags select the offset and optional parity.
        int rule = CASE_RANGES[floor(CASE_RANGES, codePoint, 16)];
        int start = rule >>> 16;
        int flags = (rule >>> 8) & 255;
        if (codePoint < start + (rule & 255) && (flags & (start ^ codePoint) & 1) == 0) {
            codePoint = (codePoint + CASE_OFFSETS[flags >>> 1]) & 65535;
        }
        int index = floor(DIACRITICS, (codePoint << 3) | 7, 0);
        int range = DIACRITICS[index];
        int folded = DIACRITIC_FOLD[index];
        if ((folded & 128) != 0 || codePoint > (range >>> 3) + (range & 7)) return codePoint;
        return folded;
    }

    private static int floor(int[] entries, int key, int shift) {
        int lo = 0, hi = entries.length - 1;
        while (lo < hi) {
            int mid = (lo + hi + 1) >>> 1;
            if ((entries[mid] >>> shift) <= key) lo = mid;
            else hi = mid - 1;
        }
        return lo;
    }
